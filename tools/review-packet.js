#!/usr/bin/env node
// Clinical review packet (M3): regenerates a deterministic markdown summary of
// current thresholds, symptom/staging tables, scenario metrics, and the model
// card — the artifact a clinician can actually review. Re-run after any config
// or model change. Deliberately timestamp-free so the packet diffs cleanly.

import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { DEFAULT_CONFIG } from '../core/config.js';
import { STAGE_DEFINITIONS } from '../core/care.js';
import { SYMPTOM_KEYS, SYMPTOM_LABELS } from '../core/symptoms.js';
import { FEATURE_LABELS } from '../core/features.js';
import { evaluateScenarios } from './evaluate.js';

const cfg = DEFAULT_CONFIG;
const lines = [];
const push = (text = '') => lines.push(text);

push('# SisFall review packet (M3)');
push();
push('Generated by `tools/review-packet.js`. Re-run after any config or model change.');
push('No timestamps by design — the packet is git-diffable. Prototype only, not a medical device.');
push();

push('## Purpose & scope');
push();
push('Fall-prevention agent: predicts dangerous postures from camera pose or IMU streams,');
push('fuses non-motion symptom check-ins, classifies longitudinal risk into stages 0-3, and');
push('emits stage-matched advice. This packet lists every threshold a clinical reviewer');
push('would need to judge, plus current scenario metrics.');
push();

push('## Risk features & bands (`config.risk`)');
push();
for (const [key, label] of Object.entries(FEATURE_LABELS)) {
  const scale = cfg.risk.scales[key];
  push(`- **${label}** — weight ${cfg.risk.weights[key]}, pressure 0 at ${scale.start}, saturates at ${scale.full}`);
}
push(`- Bands: caution ≥ ${cfg.risk.thresholds.caution}, danger ≥ ${cfg.risk.thresholds.danger} (0-100 scale)`);
push(`- Coverage discounts: measured ${cfg.risk.coverageWeight.measured}, proxy ${cfg.risk.coverageWeight.proxy}, unavailable ${cfg.risk.coverageWeight.unavailable}`);
push();

push('## Prediction gates (`config.forecast`)');
push();
push(`- Rise rate ≥ ${cfg.forecast.minRiseRate} pts/s, fit confidence ≥ ${cfg.forecast.minConfidence}, score floor ${cfg.forecast.scoreFloor}`);
push(`- Imminent horizon ${cfg.forecast.imminentHorizonSec} s, danger horizon ${cfg.forecast.dangerHorizonSec} s (extended by active symptoms)`);
push(`- Staggering index floor ${cfg.forecast.instabilityFloor} at score ≥ ${cfg.forecast.instabilityScoreFloor}`);
push();

push('## Escalation policy (`config.policy`)');
push();
push(`- Exit lines: caution ${cfg.policy.cautionExit}, danger ${cfg.policy.dangerExit}; recovery hold ${cfg.policy.recoverHoldSec} s`);
push(`- Cooldowns: audio ${cfg.policy.audioCooldownSec} s, cues ${cfg.policy.cueCooldownSec} s; reminders every ${cfg.policy.reminderIntervalSec} s`);
push();

push('## Symptom model (`config.symptoms`)');
push();
for (const key of SYMPTOM_KEYS) {
  push(`- **${SYMPTOM_LABELS[key]}** — half-life ${Math.round(cfg.symptoms.halfLifeSec[key] / 60)} min, effective-score boost ${cfg.symptoms.riskBoost[key]} (cap ${cfg.symptoms.boostCap}), forecast horizon ×${cfg.symptoms.horizonScale[key]}`);
}
push(`- Stage floors: ${cfg.staging.symptomFloors.map((r) => `${r.symptom} ≥ ${r.level} ⇒ stage ≥ ${r.minStage}`).join('; ')}`);
push();

push('## Staging (`config.staging`)');
push();
push(`- Evidence window ${cfg.staging.evidenceWindowSec / 60} min; weights (episodes/time-in-band/gait-variability/symptoms): ${Object.values(cfg.staging.weights).join(' / ')}`);
push(`- Thresholds: guarded ≥ ${cfg.staging.thresholds.guarded}, fragile ≥ ${cfg.staging.thresholds.fragile}, high-risk ≥ ${cfg.staging.thresholds.high}; provisional under ${cfg.staging.minEvidenceSec} s of evidence`);
for (const stage of STAGE_DEFINITIONS) {
  push(`- **${stage.label}** — ${stage.summary} Review cadence: ${stage.reviewInDays} day(s).${stage.escalation ? ' Recommends professional contact.' : ''}`);
}
push();

push('## Scenario evaluation (rules path, seeds 1-6)');
push();
const { summary } = evaluateScenarios();
for (const [name, stats] of Object.entries(summary)) {
  const lead = stats.meanLeadSec == null ? 'n/a' : `${stats.meanLeadSec.toFixed(2)} s (min ${stats.minLeadSec.toFixed(2)} s)`;
  push(`- **${name}**: ${stats.runs} runs · audio alarms ${stats.audioActions} · acute-state runs ${stats.acuteRuns} · danger runs ${stats.dangerRuns} · alarmed ${stats.alarmedRuns} · missed ${stats.missedRuns} · mean lead ${lead}`);
}
push();

push('## Learned model card');
push();
try {
  const artifact = JSON.parse(await readFile(new URL('../models/risk-v1.json', import.meta.url), 'utf8'));
  push(`- Version ${artifact.version}; provenance source: ${artifact.trainedOn?.source ?? 'unknown'}`);
  push(`- Validation AUC ${artifact.metrics.auc.toFixed(3)}, F1 ${artifact.metrics.f1.toFixed(3)} (precision ${artifact.metrics.precision.toFixed(3)}, recall ${artifact.metrics.recall.toFixed(3)}) at threshold ${artifact.threshold.toFixed(3)}`);
  push(`- Windows: ${artifact.metrics.nTrain} train / ${artifact.metrics.nValidation} validation, ${artifact.metrics.positives} positives (run-wise split)`);
  push(`- Limitations: ${artifact.limitations}`);
} catch {
  push('- No model artifact found (run `npm run train`). The agent is running the rule-based scorer.');
}
push();

push('## Open questions for clinical review');
push();
push('1. Are the 42/72 score bands consistent with clinical intuition for the target population, or should they be population-specific?');
push('2. Symptom half-lives are engineering estimates — do they match typical dizziness/fatigue episode durations?');
push('3. Staging weights (episodes 0.30 / time-in-band 0.30 / gait variability 0.35 / symptoms 0.05) were chosen for face validity — what weighting would a clinician choose?');
push('4. Which escalation actions are acceptable without explicit caregiver consent flows (stage 3 recommends contact; nothing is automatic)?');
push('5. What false-alarm rate is tolerable per monitoring hour in the target setting (nursing home vs. independent living)?');
push('6. Should symptom check-ins be clinically validated instruments (e.g., numeric rating scales) rather than 0-1 severity chips?');
push();

await mkdir('reports', { recursive: true });
await writeFile('reports/review-packet.md', `${lines.join('\n')}\n`);
console.log('wrote reports/review-packet.md');
